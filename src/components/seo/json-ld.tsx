/**
 * Structured data for search engines (F12), as the Next.js JSON-LD guide
 * recommends. "<" is escaped, so text from an ad (a title, for example) can
 * never close the script tag.
 */
export function JsonLd({ data }: { data: Record<string, unknown> | Record<string, unknown>[] }) {
  return (
    <script
      type="application/ld+json"
      dangerouslySetInnerHTML={{ __html: JSON.stringify(data).replace(/</g, "\\u003c") }}
    />
  );
}

/** A BreadcrumbList from [name, absolute url] pairs. */
export function breadcrumbList(items: [string, string][]) {
  return {
    "@context": "https://schema.org",
    "@type": "BreadcrumbList",
    itemListElement: items.map(([name, item], i) => ({ "@type": "ListItem", position: i + 1, name, item })),
  };
}
